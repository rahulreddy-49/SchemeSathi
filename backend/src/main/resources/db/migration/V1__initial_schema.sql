-- V1__initial_schema.sql
-- SchemeSathi PostgreSQL Initial Schema Migration
-- Matches all JPA entity definitions: User, Scheme, EligibilityRule, RequiredDocument,
-- CitizenProfile, CitizenDocument, SavedScheme

-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(15),
    role VARCHAR(20) NOT NULL DEFAULT 'CITIZEN',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);

-- 2. Schemes Table
CREATE TABLE IF NOT EXISTS schemes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(300) NOT NULL,
    description TEXT,
    objective TEXT,
    government_authority VARCHAR(200),
    scope VARCHAR(20) NOT NULL DEFAULT 'CENTRAL',
    state VARCHAR(50),
    benefit_category VARCHAR(50),
    benefits TEXT,
    application_process TEXT,
    official_url VARCHAR(500),
    application_url VARCHAR(500),
    source VARCHAR(200),
    verification_date DATE,
    deadline DATE,
    active BOOLEAN DEFAULT TRUE,
    important_warnings TEXT,
    common_rejection_reasons TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_schemes_active ON schemes(active);
CREATE INDEX IF NOT EXISTS idx_schemes_scope ON schemes(scope);
CREATE INDEX IF NOT EXISTS idx_schemes_state ON schemes(state);
CREATE INDEX IF NOT EXISTS idx_schemes_benefit_category ON schemes(benefit_category);

-- 3. Eligibility Rules Table
CREATE TABLE IF NOT EXISTS eligibility_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id BIGINT NOT NULL,
    criterion_field VARCHAR(50) NOT NULL,
    operator VARCHAR(30) NOT NULL,
    criterion_value VARCHAR(200) NOT NULL,
    display_label VARCHAR(200),
    description VARCHAR(500),
    mandatory BOOLEAN DEFAULT TRUE,
    priority INTEGER DEFAULT 0,
    CONSTRAINT fk_eligibility_rules_scheme FOREIGN KEY (scheme_id) REFERENCES schemes(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_eligibility_rules_scheme_id ON eligibility_rules(scheme_id);

-- 4. Required Documents Table
CREATE TABLE IF NOT EXISTS required_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id BIGINT NOT NULL,
    document_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    mandatory BOOLEAN DEFAULT TRUE,
    alternatives VARCHAR(200),
    CONSTRAINT fk_required_documents_scheme FOREIGN KEY (scheme_id) REFERENCES schemes(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_required_documents_scheme_id ON required_documents(scheme_id);

-- 5. Citizen Profiles Table
CREATE TABLE IF NOT EXISTS citizen_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    age INTEGER,
    gender VARCHAR(10),
    state VARCHAR(50),
    district VARCHAR(100),
    occupation VARCHAR(50),
    annual_income DOUBLE PRECISION,
    education_level VARCHAR(50),
    category VARCHAR(30),
    disability_status BOOLEAN DEFAULT FALSE,
    disability_type VARCHAR(50),
    disability_percentage INTEGER,
    land_ownership BOOLEAN DEFAULT FALSE,
    land_area DOUBLE PRECISION,
    employment_status VARCHAR(30),
    residence_type VARCHAR(30),
    marital_status VARCHAR(30),
    family_size INTEGER,
    bpl_status BOOLEAN DEFAULT FALSE,
    ration_card_type VARCHAR(30),
    minority_status BOOLEAN DEFAULT FALSE,
    ex_serviceman BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_citizen_profiles_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_citizen_profiles_user UNIQUE (user_id)
);

CREATE INDEX IF NOT EXISTS idx_citizen_profiles_state ON citizen_profiles(state);

-- 6. Citizen Documents Table
CREATE TABLE IF NOT EXISTS citizen_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    document_type VARCHAR(100) NOT NULL,
    file_name VARCHAR(200),
    file_path VARCHAR(500),
    status VARCHAR(30) DEFAULT 'UPLOADED',
    extracted_data TEXT,
    confidence DOUBLE PRECISION,
    notes VARCHAR(500),
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verified_at TIMESTAMP,
    expiry_date TIMESTAMP,
    CONSTRAINT fk_citizen_documents_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_citizen_documents_user_id ON citizen_documents(user_id);
CREATE INDEX IF NOT EXISTS idx_citizen_documents_user_type ON citizen_documents(user_id, document_type);

-- 7. Saved Schemes Table
CREATE TABLE IF NOT EXISTS saved_schemes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    scheme_id BIGINT NOT NULL,
    notes VARCHAR(500),
    saved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_saved_schemes_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_saved_schemes_scheme FOREIGN KEY (scheme_id) REFERENCES schemes(id) ON DELETE CASCADE,
    CONSTRAINT uk_saved_schemes_user_scheme UNIQUE (user_id, scheme_id)
);

CREATE INDEX IF NOT EXISTS idx_saved_schemes_user_id ON saved_schemes(user_id);
CREATE INDEX IF NOT EXISTS idx_saved_schemes_scheme_id ON saved_schemes(scheme_id);
