-- Household Member Profiles for Family Eligibility Evaluation

CREATE TABLE IF NOT EXISTS household_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    relationship VARCHAR(30) NOT NULL,
    age INTEGER,
    gender VARCHAR(10),
    state VARCHAR(50),
    district VARCHAR(100),
    occupation VARCHAR(50),
    annual_income DOUBLE PRECISION,
    education_level VARCHAR(50),
    category VARCHAR(30),
    disability_status BOOLEAN DEFAULT FALSE,
    disability_type VARCHAR(50),
    disability_percentage INTEGER,
    land_ownership BOOLEAN DEFAULT FALSE,
    land_area DOUBLE PRECISION,
    employment_status VARCHAR(30),
    residence_type VARCHAR(30),
    marital_status VARCHAR(30),
    family_size INTEGER,
    bpl_status BOOLEAN DEFAULT FALSE,
    ration_card_type VARCHAR(30),
    minority_status BOOLEAN DEFAULT FALSE,
    ex_serviceman BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_household_members_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_household_member_user_name_rel UNIQUE (user_id, full_name, relationship)
);

CREATE INDEX IF NOT EXISTS idx_household_members_user_id ON household_members(user_id);
