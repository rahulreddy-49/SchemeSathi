-- V3__application_tracking.sql
-- Government Scheme Application Tracking & Audit History

CREATE TABLE IF NOT EXISTS scheme_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    scheme_id BIGINT NOT NULL,
    household_member_id BIGINT NULL,
    applicant_type VARCHAR(20) NOT NULL DEFAULT 'SELF',
    applicant_name VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PLANNING',
    application_reference VARCHAR(100),
    applied_date DATE,
    last_status_update TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_action_date DATE,
    next_action_notes VARCHAR(500),
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_scheme_applications_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_scheme_applications_scheme FOREIGN KEY (scheme_id) REFERENCES schemes(id) ON DELETE CASCADE,
    CONSTRAINT fk_scheme_applications_household_member FOREIGN KEY (household_member_id) REFERENCES household_members(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_scheme_applications_user_id ON scheme_applications(user_id);
CREATE INDEX IF NOT EXISTS idx_scheme_applications_scheme_id ON scheme_applications(scheme_id);
CREATE INDEX IF NOT EXISTS idx_scheme_applications_hh_member ON scheme_applications(household_member_id);
CREATE INDEX IF NOT EXISTS idx_scheme_applications_status ON scheme_applications(user_id, status);

CREATE TABLE IF NOT EXISTS scheme_application_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    from_status VARCHAR(30),
    to_status VARCHAR(30) NOT NULL,
    notes VARCHAR(500),
    initiated_by VARCHAR(50) NOT NULL DEFAULT 'CITIZEN',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_scheme_app_history_application FOREIGN KEY (application_id) REFERENCES scheme_applications(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_scheme_app_history_app_id ON scheme_application_history(application_id);
CREATE INDEX IF NOT EXISTS idx_scheme_app_history_created_at ON scheme_application_history(application_id, created_at);
